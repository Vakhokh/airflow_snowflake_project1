CREATE SCHEMA ECOM_DWH.SANDBOX;


CREATE TABLE ECOM_DWH.SANDBOX.TEST_2_LOG (
    log_id      INT AUTOINCREMENT,
    p_date      DATE,
    p_ts        TIMESTAMP_NTZ(9),
    p_prev_date DATE,
    called_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE PROCEDURE ECOM_DWH.SANDBOX.TEST_2(P_DATE DATE, P_TS TIMESTAMP_NTZ, P_PREV_DATE DATE)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    INSERT INTO ECOM_DWH.SANDBOX.TEST_2_LOG (p_date, p_ts, p_prev_date)
    VALUES (:P_DATE, :P_TS, :P_PREV_DATE);
    RETURN 'logged';
END;
$$;

